<?php

declare(strict_types=1);

namespace Zana\Ddd\Tests\Domain;

use PHPUnit\Framework\TestCase;
use Zana\Ddd\Domain\DomainEvent;

class DomainEventTest extends TestCase
{
    public function testEventHasAutoGeneratedId(): void
    {
        $event = new TestDomainEvent();

        $this->assertNotNull($event->getEventId());
        $this->assertStringStartsWith('evt-', $event->getEventId());
    }

    public function testEventWithCustomId(): void
    {
        $event = new TestDomainEvent('custom-event-id');
        $this->assertEquals('custom-event-id', $event->getEventId());
    }

    public function testEventHasOccurredAt(): void
    {
        $event = new TestDomainEvent();
        $this->assertInstanceOf(\DateTimeImmutable::class, $event->getOccurredAt());
    }

    public function testEventNameIsClassName(): void
    {
        $event = new TestDomainEvent();
        $this->assertEquals(TestDomainEvent::class, $event->getEventName());
    }
}

class TestDomainEvent extends DomainEvent
{
}


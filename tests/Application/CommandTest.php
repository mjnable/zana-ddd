<?php

declare(strict_types=1);

namespace Zana\Ddd\Tests\Application;

use PHPUnit\Framework\TestCase;
use Zana\Ddd\Application\Command;

class CommandTest extends TestCase
{
    public function testCommandHasAutoGeneratedId(): void
    {
        $command = new TestCommand();

        $this->assertNotNull($command->getCommandId());
        $this->assertStringStartsWith('cmd-', $command->getCommandId());
    }

    public function testCommandHasCreatedAt(): void
    {
        $command = new TestCommand();
        $this->assertInstanceOf(\DateTimeImmutable::class, $command->getCreatedAt());
    }

    public function testEachCommandHasUniqueId(): void
    {
        $command1 = new TestCommand();
        $command2 = new TestCommand();

        $this->assertNotEquals($command1->getCommandId(), $command2->getCommandId());
    }
}

class TestCommand extends Command
{
}


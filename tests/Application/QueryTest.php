<?php

declare(strict_types=1);

namespace Zana\Ddd\Tests\Application;

use PHPUnit\Framework\TestCase;
use Zana\Ddd\Application\Query;

class QueryTest extends TestCase
{
    public function testQueryHasAutoGeneratedId(): void
    {
        $query = new TestQuery();

        $this->assertNotNull($query->getQueryId());
        $this->assertStringStartsWith('qry-', $query->getQueryId());
    }

    public function testQueryHasCreatedAt(): void
    {
        $query = new TestQuery();
        $this->assertInstanceOf(\DateTimeImmutable::class, $query->getCreatedAt());
    }

    public function testEachQueryHasUniqueId(): void
    {
        $query1 = new TestQuery();
        $query2 = new TestQuery();

        $this->assertNotEquals($query1->getQueryId(), $query2->getQueryId());
    }
}

class TestQuery extends Query
{
}

